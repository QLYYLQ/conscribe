        with temp_package(tmp_path, "aliaspkg", files):
            from aliaspkg.owner import Owner

            source = _stub_for(Owner)
            assert "from aliaspkg.a import Config" in source
            assert "from aliaspkg.b import Config as BConfig" in source
            assert "def setup(self, first: Config, second: BConfig | None = None) -> None: ..." in source
            assert_valid_stub(source)


