def _info(
    cls: type,
    *,
    injected: tuple[InjectedAttr, ...] = (InjectedAttr("dummy", str, None),),
    module: str | None = None,
) -> ClassStubInfo:
    """Stub info for any class (members collected for real)."""
    members = collect_class_members(cls, skip=frozenset(a.name for a in injected))
    return ClassStubInfo(
        cls=cls,
        class_name=cls.__name__,
        module=module or cls.__module__,
        source_file=None,
        bases=tuple(cls.__bases__),
        injected_attrs=injected,
        init=members.init,
        methods=members.methods,
        class_attrs=members.class_attrs,
        values=members.values,
        nested=members.nested,
    )


def _owner(name: str, **members: object) -> type:
    """A class with a plain qualified name (as if module-level) holding *members*."""
    return type(name, (), {"__module__": __name__, **members})


def _stub_for(cls: type, **kwargs) -> str:
    info = _info(cls, **kwargs)
    return generate_module_stub(info.module, [info])


# ── Structure ────────────────────────────────────────────────────


class TestStructure:
    def test_empty_classes(self):
        assert generate_module_stub("mod", []) == ""

    def test_basic_structure(self):
        Foo = type("Foo", (), {})
        info = _info(Foo, injected=(InjectedAttr("env", Terminal, "test_env"),), module="mymod")
        source = generate_module_stub("mymod", [info])

        lines = source.splitlines()
        assert lines[0].startswith("# Generated by conscribe ")
        assert lines[1] == "# DO NOT EDIT. Stub for module: mymod"
        assert "from __future__ import annotations" in source
        assert "def __getattr__(name: str) -> Any: ..." in source
        assert "class Foo:" in source
        assert "env: Terminal  # wired from: test_env" in source
        # Terminal lives in this test module: imported by short name.
        assert f"from {__name__} import Terminal" in source

    def test_same_module_base_becomes_nominal_placeholder(self):
        source = _stub_for(PlaceholderChild)
        assert "class PlaceholderBase(Any): ..." in source
        assert "class PlaceholderChild(PlaceholderBase):" in source
        assert source.index("class PlaceholderBase(Any)") < source.index("class PlaceholderChild(")
        assert_valid_stub(source)

    def test_imported_base(self):
        source = _stub_for(AbcChild)
        assert "from abc import ABC" in source
        assert "class AbcChild(ABC):" in source

    def test_init_rendered(self):
        source = _stub_for(InitDefault)
        assert "def __init__(self, name: str = 'default') -> None: ..." in source

    def test_init_without_return_annotation_gets_none(self):
        assert "def __init__(self, name: str = 'default') -> None: ..." in _stub_for(InitNoReturn)

    def test_methods_and_decorators_rendered(self):
        body = class_body(_stub_for(Decorated), "Decorated")
        assert "def step(self, task: str) -> str: ..." in body
        assert "def reset(self): ..." in body
        assert "@classmethod\n    def create(cls) -> Decorated: ..." in body
        assert "@staticmethod\n    def helper(x: int) -> int: ..." in body
        assert "@property\n    def size(self) -> int: ..." in body
        assert "@size.setter\n    def size(self, value: int) -> None: ..." in body

    def test_mode3_literal_uses_str(self):
        Foo = type("Foo", (), {})
        source = _stub_for(Foo, injected=(InjectedAttr("browser", str, None),))
        assert "browser: str\n" in source

    def test_compilable_output(self):
        _make_env_registry()

        info = collect_class_stub_info(CompilableAgent)
        assert info is not None
        source = generate_module_stub(info.module, [info])
        compile(source, "<test>", "exec")
        assert "env: EnvProtocol  # wired from: test_env" in source
        assert_valid_stub(source)

    def test_multiple_classes_same_module(self):
        Foo = type("Foo", (), {})
        Bar = type("Bar", (), {})
        source = generate_module_stub(__name__, [_info(Foo), _info(Bar)])
        assert "class Foo:" in source
        assert "class Bar:" in source

    def test_class_listed_twice_is_rendered_once(self):
        Foo = type("Foo", (), {})
        info = _info(Foo)
        source = generate_module_stub(__name__, [info, info])
        assert source.count("class Foo:") == 1

    def test_same_module_protocol_is_rendered_structurally(self):
        """A nominal placeholder would make every implementation a type error."""
        Foo = type("Foo", (), {})
        source = _stub_for(Foo, injected=(InjectedAttr("env", EnvProtocol, "test_env"),))
        assert "@runtime_checkable\nclass EnvProtocol(Protocol):\n    def setup(self) -> None: ..." in source
        assert "env: EnvProtocol  # wired from: test_env" in source
        assert_valid_stub(source)


