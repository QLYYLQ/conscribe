class TestEvaluatedAnnotations:
    """No PEP 563: 1.3.0 rendered these with inspect.formatannotation."""

    @pytest.fixture(scope="class")
    def source(self) -> str:
        from tests.stubs.fixtures.evaluated import Evaluated

        return _stub_for(Evaluated)

    def test_valid(self, source):
        assert_valid_stub(source)
        for bad in ("FieldInfo(", "NoneType", "<", "tests.stubs.fixtures.evaluated."):
            assert bad not in source.replace("->", ""), bad

    def test_no_any_bindings(self, source):
        assert not re.search(r"^\w+ = Any$", source, flags=re.M)

    def test_class_attrs_keep_their_arguments(self, source):
        body = class_body(source, "Evaluated")
        for line in (
            "a: int | None",
            "b: List[str]",
            "c: Dict[str, int]",
            "d: int",
            "e: Literal['x', 'y']",
            "f: ClassVar[int]",
            "g: Color | None",
        ):
            assert f"    {line}\n" in body, line

    @pytest.mark.parametrize(
        "param",
        [
            "depth: int = 1",
            "color: Literal[Color.RED, Color.BLUE] = ...",
            "level: Level | None = None",
            "picker: Picker | None = None",
            "options: Options | None = None",
            "box: Box[int] | None = None",
            "user: UserId | None = None",
            "inner: Outer.Inner | None = None",
            "callback: Callable[[int, str], bool] | None = None",
            "anything: Callable[..., Any] = ...",
            "pair: tuple[int, int] = (0, 0)",
            "rest: Tuple[int, ...] = ()",
            "empty: tuple[()] = ()",
            "typed: List[int] = []",
            "iterable: Iterable[str] | None = None",
            "settings: Settings | None = None",
            "kind: type[Picker] = ...",
        ],
    )
    def test_constructor_parameters(self, source, param):
        assert param in source

    def test_same_module_definitions(self, source):
        assert "class Color(Enum):\n    RED = 'r'\n    BLUE = 'b'\n" in source
        assert "class Level(IntEnum):\n    LOW = 1\n    HIGH = 2\n\n    def describe(self) -> str: ...\n" in source
        assert (
            "@runtime_checkable\nclass Picker(Protocol):\n    name: str\n\n"
            "    def pick(self, items: list[int]) -> int: ...\n"
        ) in source
        assert "class Options(TypedDict, total=False):\n    retries: int\n    label: str\n" in source
        assert "T = TypeVar('T')" in source
        assert "class Box(Any, Generic[T]): ..." in source
        assert source.index("T = TypeVar('T')") < source.index("class Box(")
        assert "UserId = NewType('UserId', int)" in source
        assert "class Outer(Any):\n    class Inner(Any): ...\n" in source
        assert "class Settings(Any): ..." in source

    def test_generic_method(self, source):
        assert "def first(self, items: list[T]) -> T: ..." in source

    def test_identical_on_every_python_version(self, source):
        """Pinned text: the 3.10 and 3.14 test runs check the same output."""
        assert "from typing import Any, Callable, ClassVar, Dict, Generic, List, Literal" in source
        assert "from collections.abc import Iterable" in source
        assert "from enum import Enum, IntEnum" in source


