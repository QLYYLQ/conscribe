class TestRefusals:
    def test_literal_value_that_has_no_source_form(self):
        with pytest.raises(ConfigRenderError, match="Literal values must be") as excinfo:
            _stub_for(WeirdLiteral)
        assert "WeirdLiteral.f(x)" in str(excinfo.value)

    def test_value_that_is_not_a_type(self):
        with pytest.raises(ConfigRenderError, match="not a type"):
            _stub_for(WeirdValue)

    def test_object_that_cannot_be_imported_or_defined(self):
        from tests.stubs.fixtures.unreachable import HIDDEN

        def f(self, x) -> None: ...

        f.__annotations__["x"] = HIDDEN[0]  # an evaluated annotation
        with pytest.raises(ConfigRenderError, match="cannot be imported by name"):
            _stub_for(_owner("HiddenOwner", f=f))

    def test_two_classes_sharing_a_name(self):
        def make():
            class Twin:
                pass

            return Twin

        def f(self, a, b) -> None: ...

        f.__annotations__.update(a=make(), b=make())  # evaluated annotations
        with pytest.raises(ConfigRenderError, match="two different objects named 'Twin'"):
            _stub_for(_owner("TwinOwner", f=f))

    def test_two_stubbed_classes_sharing_a_name(self):
        with pytest.raises(ConfigRenderError, match="two different classes named 'Agent'"):
            generate_module_stub(__name__, [_info(_owner("Agent")), _info(_owner("Agent"))])

    def test_function_local_class_is_refused(self):
        """Before 2.0 it was written as a top-level class its module does not have."""

        class Local:
            pass

        with pytest.raises(ConfigRenderError, match="defined inside a function") as excinfo:
            _stub_for(Local)
        assert "test_function_local_class_is_refused.<locals>.Local" in str(excinfo.value)


# ── Function-local classes ───────────────────────────────────────


class TestFunctionLocalNames:
    def test_local_name_degrades_to_any_with_a_warning(self):
        class LocalType:
            pass

        @runtime_checkable
        class LocalProto(Protocol):
            def f(self, x: LocalType) -> None: ...

        def use(self, p) -> None: ...

        use.__annotations__["p"] = LocalProto  # an evaluated annotation
        # The referenced Protocol is defined in the stub; PEP 563 makes
        # ``LocalType`` in its member a string only the enclosing function's
        # locals can resolve: conscribe cannot see them.
        with pytest.warns(ExtractionWarning, match="LocalType"):
            source = _stub_for(_owner("UsesLocalProto", use=use))
        assert "def f(self, x: Any) -> None: ..." in source
        assert "def use(self, p: LocalProto) -> None: ..." in source


