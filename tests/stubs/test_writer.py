def _files(root: Path) -> list[str]:
    return sorted(p.relative_to(root).as_posix() for p in root.rglob("*.pyi"))


#: A stub header as conscribe 2.x writes it, and as 1.x wrote it.
HEADER_2 = "# Generated by conscribe 2.0.0\n# DO NOT EDIT. Stub for module: {module}\n"
HEADER_1 = "# Auto-generated by conscribe. DO NOT EDIT.\n# Stub file for: {module}\n"


# One layer with one module of implementations (``impls.py``).
_ENV_REG = """
    from typing import Protocol, runtime_checkable
    from conscribe import create_registrar

    @runtime_checkable
    class Env(Protocol):
        def setup(self) -> None: ...

    Envs = create_registrar("{pkg}_env", Env, discriminator_field="name")

    class Base(metaclass=Envs.Meta):
        __abstract__ = True
        def setup(self) -> None: ...
"""


def _env(pkg: str, impls: str) -> dict[str, str]:
    return {"reg.py": _ENV_REG.replace("{pkg}", pkg), "impls.py": impls.replace("{pkg}", pkg)}


class TestWriteLayerStubs:
    def test_no_wired_classes(self, tmp_path):
        """No classes with injected wiring → nothing written."""
        impls = """
            from {pkg}.reg import Base

            class PlainImpl(Base):
                def setup(self) -> None: ...
        """
        with temp_package(tmp_path / "src", "wenv_a", _env("wenv_a", impls)):
            import wenv_a.impls  # noqa: F401
            from wenv_a.reg import Envs

            out = tmp_path / "stubs"
            assert write_layer_stubs(Envs, output_dir=out) == []
            assert not out.exists()

    def test_writes_pyi_to_output_dir(self, tmp_path):
        """Classes with injected wiring → .pyi written to output_dir (module path mirrored)."""
        impls = """
            from {pkg}.reg import Base

            class WiredImpl(Base):
                __wiring__ = {"dep": ["some_value"]}

                def setup(self) -> None: ...
        """
        with temp_package(tmp_path / "src", "wenv_b", _env("wenv_b", impls)):
            import wenv_b.impls  # noqa: F401
            from wenv_b.reg import Envs

            out = tmp_path / "stubs"
            written = write_layer_stubs(Envs, output_dir=out)
            assert written == [out / "wenv_b" / "impls.pyi"]
            content = written[0].read_text()
            assert_valid_stub(content)
        assert "dep: str" in content
        assert "class WiredImpl(Base):" in content
        assert "from wenv_b.reg import Base" in content

    def test_partial_class_fallback_passed_through(self, tmp_path):
        impls = """
            from {pkg}.reg import Base

            class WiredImpl3(Base):
                __wiring__ = {"dep": ["val"]}

                def setup(self) -> None: ...
        """
        with temp_package(tmp_path / "src", "wenv_c", _env("wenv_c", impls)):
            import wenv_c.impls  # noqa: F401
            from wenv_c.reg import Envs

            (path,) = write_layer_stubs(Envs, output_dir=tmp_path / "stubs", partial_class_fallback=True)
            content = path.read_text()
        assert "from _typeshed import Incomplete" in content
        assert "def __getattr__(self, name: str) -> Incomplete: ..." in content

    def test_multi_key_class_is_rendered_once(self, tmp_path):
        """1.3.0 iterated keys: the class appeared twice (pyright reportRedeclaration)."""
        impls = """
            from {pkg}.reg import Base

            class Multi(Base):
                __registry_key__ = ["multi_a", "multi_b"]
                __wiring__ = {"dep": ["val"]}

                def setup(self) -> None: ...
        """
        with temp_package(tmp_path / "src", "wenv_d", _env("wenv_d", impls)):
            import wenv_d.impls  # noqa: F401
            from wenv_d.reg import Envs

            assert set(Envs.keys()) >= {"multi_a", "multi_b"}
            (path,) = write_layer_stubs(Envs, output_dir=tmp_path / "stubs")
            content = path.read_text()
            assert_valid_stub(content)
        assert content.count("class Multi(") == 1

    def test_empty_layer_raises(self, env_registrar, tmp_path):
        """Like build_layer_config: an empty layer means discover() missed its package (C1)."""
        with pytest.raises(EmptyLayerError, match="test_env_writer"):
            write_layer_stubs(env_registrar, output_dir=tmp_path)
        assert _files(tmp_path) == []


# Two modules of one layer: ``good.py`` would get a stub, ``bad.py`` is broken.
_LAYER = {
    "reg.py": """
        from typing import Protocol, runtime_checkable
        from conscribe import create_registrar

        @runtime_checkable
        class Strategy(Protocol):
            def pick(self) -> int: ...

        @runtime_checkable
        class Tool(Protocol):
            def use(self) -> None: ...

        Strat = create_registrar("{pkg}_strat", Strategy, discriminator_field="strategy_id")
        Tools = create_registrar("{pkg}_tool", Tool, discriminator_field="tool_id")

        class StratBase(metaclass=Strat.Meta):
            __abstract__ = True
            def pick(self) -> int: return 0

        class Fast(StratBase):
            __registry_key__ = "fast"

        class ToolBase(metaclass=Tools.Meta):
            __abstract__ = True
            def use(self) -> None: ...
    """,
    "good.py": """
        from {pkg}.reg import ToolBase

        class Good(ToolBase):
            __registry_key__ = "good"
            __wiring__ = {"strategy": "{pkg}_strat"}
    """,
}

#: ``bad.py`` that injects nothing (no stub).
NOT_WIRED = """
    from {pkg}.reg import ToolBase

    class NotWired(ToolBase):
        __registry_key__ = "not_wired"
"""


def _layer(pkg: str, bad_source: str) -> dict[str, str]:
    files = {name: source.replace("{pkg}", pkg) for name, source in _LAYER.items()}
    files["bad.py"] = bad_source.replace("{pkg}", pkg)
    return files


class TestNothingWrittenOnFailure:
    def test_wiring_problem_raises_before_any_file_is_written(self, tmp_path):
        bad = """
            from {pkg}.reg import ToolBase

            class Bad(ToolBase):
                __registry_key__ = "bad"
                __wiring__ = {"strategy": ("{pkg}_strat", ["fsat"])}
        """
        with temp_package(tmp_path / "src", "writerpkg_a", _layer("writerpkg_a", bad)):
            import writerpkg_a.bad  # noqa: F401
            import writerpkg_a.good  # noqa: F401
            from writerpkg_a.reg import Tools

            out = tmp_path / "stubs"
            with pytest.raises(WiringResolutionError) as excinfo:
                write_layer_stubs(Tools, output_dir=out)
            assert [p.kind for p in excinfo.value.problems] == ["unknown_key"]
            assert "Bad (key 'bad') wiring 'strategy': unknown key 'fsat'" in str(excinfo.value)
            assert not out.exists()

    def test_render_failure_raises_before_any_file_is_written(self, tmp_path):
        bad = """
            from typing import Literal
            from {pkg}.reg import ToolBase

            class Bad(ToolBase):
                __registry_key__ = "bad"
                __wiring__ = {"strategy": "{pkg}_strat"}

                def tune(self, level: Literal[0.5]) -> None: ...
        """
        with temp_package(tmp_path / "src", "writerpkg_b", _layer("writerpkg_b", bad)):
            import writerpkg_b.bad  # noqa: F401
            import writerpkg_b.good  # noqa: F401
            from writerpkg_b.reg import Tools

            out = tmp_path / "stubs"
            with pytest.raises(ConfigRenderError, match=r"Bad\.tune\(level\)"):
                write_layer_stubs(Tools, output_dir=out)
            assert not out.exists()

    def test_good_layer_writes_one_file_per_module(self, tmp_path):
        with temp_package(tmp_path / "src", "writerpkg_c", _layer("writerpkg_c", NOT_WIRED)):
            import writerpkg_c.bad  # noqa: F401
            import writerpkg_c.good  # noqa: F401
            from writerpkg_c.reg import Tools

            out = tmp_path / "stubs"
            written = write_layer_stubs(Tools, output_dir=out)
            # ``bad.py`` (renamed NotWired here) injects nothing: no file.
            assert _files(out) == ["writerpkg_c/good.pyi"]
            source = written[0].read_text(encoding="utf-8")
            assert "strategy: Strategy  # wired from: writerpkg_c_strat" in source
            assert "from writerpkg_c.reg import Strategy, ToolBase" in source
            assert_valid_stub(source)


class TestFiles:
    def test_package_module_gets_an_init_stub(self, tmp_path):
        files = {
            "reg.py": _LAYER["reg.py"].replace("{pkg}", "writerpkg_e"),
            "sub/__init__.py": """
                from writerpkg_e.reg import ToolBase

                class InPackage(ToolBase):
                    __registry_key__ = "in_package"
                    __wiring__ = {"strategy": "writerpkg_e_strat"}
            """,
        }
        with temp_package(tmp_path / "src", "writerpkg_e", files) as package:
            import writerpkg_e.sub  # noqa: F401
            from writerpkg_e.reg import Tools

            out = tmp_path / "stubs"
            assert write_layer_stubs(Tools, output_dir=out) == [out / "writerpkg_e/sub/__init__.pyi"]
            assert write_layer_stubs(Tools) == [package / "sub" / "__init__.pyi"]

    def test_module_without_a_source_file_needs_output_dir(self, env_registrar, tmp_path):
        class Base(metaclass=env_registrar.Meta):
            __abstract__ = True
            def setup(self) -> None: ...

        module = types.ModuleType("conscribe_stub_test_fileless")
        sys.modules[module.__name__] = module
        try:
            namespace = {"__module__": module.__name__, "__wiring__": {"dep": ["val"]}}
            module.Base = Base
            module.Fileless = type(Base)("Fileless", (Base,), namespace)
            with pytest.raises(ConfigRenderError, match="pass output_dir"):
                write_layer_stubs(env_registrar)
            written = write_layer_stubs(env_registrar, output_dir=tmp_path)
            assert written == [tmp_path / "conscribe_stub_test_fileless.pyi"]
        finally:
            del sys.modules[module.__name__]


# ── A module shared by two layers (review ST1) ───────────────────


_SHARED = {
    "reg.py": """
        from typing import Protocol, runtime_checkable
        from conscribe import create_registrar

        @runtime_checkable
        class Strategy(Protocol):
            def pick(self) -> int: ...

        @runtime_checkable
        class Owner(Protocol):
            def run(self) -> None: ...

        Strats = create_registrar("{pkg}_strat", Strategy, discriminator_field="kind")
        Owners = create_registrar("{pkg}_owner", Owner, discriminator_field="kind")

        class StratBase(metaclass=Strats.Meta):
            __abstract__ = True
            def pick(self) -> int: return 0

        class OwnerBase(metaclass=Owners.Meta):
            __abstract__ = True
            def run(self) -> None: ...

        class Fast(StratBase):
            __registry_key__ = "fast"
    """,
    "mixed.py": """
        from {pkg}.reg import OwnerBase, StratBase

        class MixedOwner(OwnerBase):
            __registry_key__ = "mixed_owner"
            __wiring__ = {"strategy": "{pkg}_strat"}

        class MixedStrat(StratBase):
            __registry_key__ = "mixed_strat"
            __wiring__ = {"helper": "{pkg}_owner"}
    """,
}


def _shared(pkg: str) -> dict[str, str]:
    return {name: source.replace("{pkg}", pkg) for name, source in _SHARED.items()}


class TestSharedModule:
    def test_each_layer_writes_the_whole_module(self, tmp_path):
        """1.x/2.0-beta: the second layer's run overwrote the first layer's classes."""
        with temp_package(tmp_path / "src", "wshared_a", _shared("wshared_a")):
            import wshared_a.mixed  # noqa: F401
            from wshared_a.reg import Owners, Strats

            out = tmp_path / "stubs"
            first = write_layer_stubs(Owners, out)
            text_first = first[0].read_text()
            second = write_layer_stubs(Strats, out)
            text_second = second[0].read_text()
            assert first == second == [out / "wshared_a" / "mixed.pyi"]
            assert_valid_stub(text_second)
        assert text_first == text_second
        assert "strategy: Strategy" in class_body(text_second, "MixedOwner")
        assert "helper: Owner" in class_body(text_second, "MixedStrat")
        assert "strategy: Strategy  # wired from: wshared_a_strat" in text_second
        assert "helper: Owner  # wired from: wshared_a_owner" in text_second
        # Module order, whichever layer asked.
        assert text_second.index("class MixedOwner(") < text_second.index("class MixedStrat(")


# ── Stale stubs (review §4.4) ────────────────────────────────────


def _plant(directory: Path, name: str, text: str) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    path.write_text(text, encoding="utf-8")
    return path


class TestStaleStubs:
    def _setup(self, out: Path, pkg: str) -> dict[str, Path]:
        """Generated stubs this run will not write, and files that are not stale stubs."""
        directory = out / pkg
        return {
            # 2.x stub of a module that no longer needs one
            "stale": _plant(directory, "bad.pyi", HEADER_2.format(module=f"{pkg}.bad") + "x: int\n"),
            # 1.x stub of a module that does not exist any more
            "legacy": _plant(directory, "gone.pyi", HEADER_1.format(module=f"{pkg}.gone")),
            # any 2.x ``.pyi`` header counts (``# Generated by conscribe <version>``)
            "retired": _plant(
                directory, "retired.pyi",
                "# Generated by conscribe 1.9.0\n# Auto-generated by conscribe. DO NOT EDIT.\n",
            ),
            # 1.x stub this run rewrites
            "rewritten": _plant(directory, "good.pyi", HEADER_1.format(module=f"{pkg}.good")),
            # not stubs conscribe wrote: hand-written, a 1.x *config* header,
            # and a generated source file (only ``.pyi`` files are considered)
            "hand": _plant(directory, "reg.pyi", "# mine\n"),
            "config_1x": _plant(
                directory, "conf.pyi", "# Auto-generated by conscribe. DO NOT EDIT.\n# Layer: x\n"
            ),
            "source": _plant(directory, "generated.py", HEADER_2.format(module=f"{pkg}.generated")),
        }

    def test_stale_stubs_are_reported_not_deleted(self, tmp_path):
        with temp_package(tmp_path / "src", "wstale_a", _layer("wstale_a", NOT_WIRED)):
            import wstale_a.bad  # noqa: F401
            import wstale_a.good  # noqa: F401
            from wstale_a.reg import Tools

            out = tmp_path / "stubs"
            files = self._setup(out, "wstale_a")
            with pytest.warns(StaleStubWarning) as record:
                written = write_layer_stubs(Tools, output_dir=out)
        assert written == [files["rewritten"]]
        assert files["rewritten"].read_text().startswith("# Generated by conscribe")
        assert len(record) == 1
        message = str(record[0].message)
        assert "\n" not in message  # the CLI prints it as one ``Warning:`` line
        listed = message.split("type checkers: ", 1)[1].split(". Delete them", 1)[0].split(", ")
        assert listed == [str(files["stale"]), str(files["legacy"]), str(files["retired"])]
        assert "prune=True" in message and "wstale_a_tool" in message
        assert all(path.exists() for path in files.values())  # the warning deletes nothing

    def test_prune_deletes_exactly_the_stale_stubs(self, tmp_path):
        with temp_package(tmp_path / "src", "wstale_b", _layer("wstale_b", NOT_WIRED)):
            import wstale_b.bad  # noqa: F401
            import wstale_b.good  # noqa: F401
            from wstale_b.reg import Tools

            out = tmp_path / "stubs"
            files = self._setup(out, "wstale_b")
            with warnings.catch_warnings():
                warnings.simplefilter("error", StaleStubWarning)
                written = write_layer_stubs(Tools, output_dir=out, prune=True)
        assert written == [files["rewritten"]]
        for name in ("stale", "legacy", "retired"):
            assert not files[name].exists(), name
        assert files["hand"].read_text() == "# mine\n"
        assert files["config_1x"].exists() and files["source"].exists()
        assert _files(out) == ["wstale_b/conf.pyi", "wstale_b/good.pyi", "wstale_b/reg.pyi"]

    def test_stubs_next_to_the_sources(self, tmp_path):
        with temp_package(tmp_path, "wstale_c", _layer("wstale_c", NOT_WIRED)) as package:
            import wstale_c.bad  # noqa: F401
            import wstale_c.good  # noqa: F401
            from wstale_c.reg import Tools

            stale = _plant(package, "bad.pyi", HEADER_2.format(module="wstale_c.bad"))
            hand = _plant(package, "notes.pyi", "# mine\n")
            with pytest.warns(StaleStubWarning, match="bad.pyi"):
                assert write_layer_stubs(Tools) == [package / "good.pyi"]
            assert stale.exists()
            assert write_layer_stubs(Tools, prune=True) == [package / "good.pyi"]
            assert not stale.exists() and hand.exists()

    def test_another_layers_stub_is_not_stale(self, tmp_path):
        """A stub that another live registry still needs is not this run's to judge."""
        files = _shared("wstale_d")
        files["owners.py"] = """
            from wstale_d.reg import OwnerBase

            class Plain(OwnerBase):
                __registry_key__ = "plain"
        """
        files["strats.py"] = """
            from wstale_d.reg import StratBase

            class Helped(StratBase):
                __registry_key__ = "helped"
                __wiring__ = {"helper": "wstale_d_owner"}
        """
        with temp_package(tmp_path / "src", "wstale_d", files):
            import wstale_d.mixed  # noqa: F401
            import wstale_d.owners  # noqa: F401
            import wstale_d.strats  # noqa: F401
            from wstale_d.reg import Owners

            out = tmp_path / "stubs"
            # strats.py holds no class of the owner layer, but shares its directory.
            needed = _plant(out / "wstale_d", "strats.pyi", HEADER_2.format(module="wstale_d.strats"))
            with warnings.catch_warnings():
                warnings.simplefilter("error", StaleStubWarning)
                written = write_layer_stubs(Owners, output_dir=out, prune=True)
            assert written == [out / "wstale_d" / "mixed.pyi"]
            assert needed.exists()

    def test_no_warning_when_nothing_is_stale(self, tmp_path):
        with temp_package(tmp_path / "src", "wstale_e", _layer("wstale_e", NOT_WIRED)):
            import wstale_e.bad  # noqa: F401
            import wstale_e.good  # noqa: F401
            from wstale_e.reg import Tools

            with warnings.catch_warnings():
                warnings.simplefilter("error", StaleStubWarning)
                write_layer_stubs(Tools, output_dir=tmp_path / "stubs")
                write_layer_stubs(Tools, output_dir=tmp_path / "stubs")  # rerun: same files


