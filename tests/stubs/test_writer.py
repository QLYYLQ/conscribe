class TestInstalledCode:
    def test_refuses_to_write_into_site_packages(self, tmp_path):
        root = tmp_path / "lib" / "site-packages"
        with temp_package(root, "winstalled", _layer("winstalled", NOT_WIRED)) as package:
            import winstalled.bad  # noqa: F401
            import winstalled.good  # noqa: F401
            from winstalled.reg import Tools

            with pytest.raises(ConfigRenderError) as excinfo:
                write_layer_stubs(Tools)
            message = str(excinfo.value)
            assert "class Good" in message and "installed package" in message
            assert "output_dir" in message
            assert not (package / "good.pyi").exists()
            out = tmp_path / "stubs"
            assert write_layer_stubs(Tools, output_dir=out) == [out / "winstalled" / "good.pyi"]

    def test_locations(self):
        assert _installed_location(json.__file__) == "the standard library"
        assert _installed_location(pytest.__file__) == "an installed package"
        assert _installed_location(__file__) is None
