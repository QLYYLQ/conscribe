"""Write ``.pyi`` stub files for a layer, grouped by source module.

A ``.pyi`` stub replaces its whole module for type checkers, so a module's
stub is a function of the *module*, not of the layer that asked for it: it
declares every class of the module that needs a stub, whichever live
registry the class is registered in.  Running the writer for one layer
therefore never drops another layer's classes from a shared module.

Stale stubs
-----------
A stub written by an earlier run (or an earlier conscribe version) for a
module that no longer needs one still replaces that module for type
checkers.  After writing, the writer looks at the directories it is
responsible for -- where the stubs of the layer's modules go -- for
conscribe-generated stubs (recognised by their header) that this run did not
write and that no registered class needs any more.  They are reported with
a :class:`~conscribe.exceptions.StaleStubWarning`; ``prune=True`` deletes
exactly those files and nothing else.
"""
from __future__ import annotations

import functools
import inspect
import logging
import site
import sys
import sysconfig
import warnings
from collections.abc import Iterable
from pathlib import Path
from typing import Any, Union

from conscribe.exceptions import ConfigRenderError, EmptyLayerError, StaleStubWarning
from conscribe.stubs.collector import ClassStubInfo, collect_class_stub_info
from conscribe.stubs.generator import generate_module_stub

logger = logging.getLogger(__name__)

#: First lines of a ``.pyi`` file conscribe generated: ``(line 1 prefix, line 2
#: prefix)``.  2.x files start with ``# Generated by conscribe <version>``;
#: 1.x stubs started with ``# Auto-generated by conscribe.`` and
#: ``# Stub file for: <module>``.
_STUB_HEADERS: tuple[tuple[str, str], ...] = (
    ("# Generated by conscribe", ""),
    ("# Auto-generated by conscribe.", "# Stub file for:"),
)


def write_layer_stubs(
    registrar: Any,
    output_dir: Union[str, Path, None] = None,
    *,
    partial_class_fallback: bool = False,
    prune: bool = False,
) -> list[Path]:
    """Generate and write ``.pyi`` stubs for the modules of a layer that inject attributes.

    A class gets a stub entry only for ``__wiring__`` entries the framework
    injects (no runtime slot, not ``declare_only``; see
    :mod:`conscribe.stubs.collector`).  A class registered under several keys
    is rendered once.  Every module holding a class of this layer is
    (re)written when any class of it -- of this layer or of any other live
    registry -- needs a stub, and the stub declares all of those classes.
    Modules with nothing to declare get no file.

    Everything is validated and rendered before the first file is written,
    so a failure leaves the file system untouched.

    Stale stubs: conscribe-generated ``.pyi`` files (header ``# Generated by
    conscribe``, or the 1.x ``# Auto-generated by conscribe.``) in the
    directories where this layer's stubs go, that this run did not write and
    that no class registered in a live registry needs, are listed in a
    :class:`~conscribe.exceptions.StaleStubWarning`.  With ``prune=True``
    those files -- and only those -- are deleted instead.

    Args:
        registrar: A ``LayerRegistrar`` (from ``create_registrar``).
        output_dir: If given, mirror module paths under this directory
            (``pkg/mod.pyi``, ``pkg/__init__.pyi`` for a package).
            Otherwise write each ``.pyi`` next to its source ``.py`` (never
            into an installed package or the standard library).
        partial_class_fallback: When ``True``, each generated class
            includes a ``__getattr__`` returning ``Incomplete`` so type
            checkers tolerate dynamic instance attributes.  Defaults to
            ``False`` for strict type checking.
        prune: Delete the stale stubs instead of warning about them.

    Returns:
        Paths of the written ``.pyi`` files, sorted by module name.

    Raises:
        EmptyLayerError: The layer has no registered classes (``discover()``
            did not import the package holding them?).
        WiringResolutionError: Any ``__wiring__`` problem in the layer (all
            of them, at once), or in another layer's class that shares a
            module with it.
        ConfigRenderError: A module's stub cannot be written faithfully, or
            a stub has nowhere to go (no source file, or the source is in
            an installed package / the standard library, and no
            *output_dir*).
        ConfigAnnotationError: An annotation names something that exists
            nowhere.
    """
    from conscribe.wiring import validate_wiring

    layer = _layer_name(registrar)
    layer_classes = _distinct(registrar.get_all().values())
    if not layer_classes:
        raise EmptyLayerError([layer])
    validate_wiring(registrar)

    out_dir = Path(output_dir) if output_dir is not None else None
    infos = _InfoCache()
    registered = _registered_by_module()
    for cls in layer_classes:  # also when the layer's registry is shadowed in the index
        module_classes = registered.setdefault(str(cls.__module__), [])
        if all(other is not cls for other in module_classes):
            module_classes.append(cls)

    rendered: list[tuple[Path, str]] = []
    touched = sorted({str(cls.__module__) for cls in layer_classes})
    for module_name in touched:
        classes = [info for cls in registered[module_name] if (info := infos.get(cls))]
        if not classes:
            continue
        source = generate_module_stub(
            module_name,
            classes,
            partial_class_fallback=partial_class_fallback,
        )
        path = _resolve_output_path(classes, module_name, out_dir)
        rendered.append((path, source))

    written_keys = {_key(path) for path, _ in rendered}
    stale = _stale_stubs(set(touched), registered, infos, out_dir, written_keys)

    written: list[Path] = []
    for path, source in rendered:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")
        written.append(path)

    if stale and prune:
        for path in stale:
            path.unlink(missing_ok=True)
            logger.info("conscribe: deleted stale stub %s", path)
    elif stale:
        # One line (the CLI prints it as one ``Warning:`` line).
        warnings.warn(
            f"{len(stale)} stale conscribe-generated stub file(s) next to the modules of layer "
            f"{layer!r} -- not written by this run and needed by no registered class, but they "
            f"still replace their modules for type checkers: "
            f"{', '.join(str(path) for path in stale)}. Delete them, or pass prune=True "
            f"(CLI: generate-stubs --prune) to delete exactly these files.",
            StaleStubWarning,
            stacklevel=2,
        )
    return written


# ── Classes and stub infos ───────────────────────────────────────


def _layer_name(registrar: Any) -> str:
    registry = getattr(registrar, "_registry", None)
    name = getattr(registry, "name", None)
    return name if isinstance(name, str) else repr(registrar)


def _distinct(classes: Iterable[type]) -> list[type]:
    """Each class once (multi-key and multi-registry registrations), first-seen order."""
    seen: set[int] = set()
    result: list[type] = []
    for cls in classes:
        if id(cls) not in seen:
            seen.add(id(cls))
            result.append(cls)
    return result


def _registered_by_module() -> dict[str, list[type]]:
    """``{module: [class, ...]}`` of every class in every live registry."""
    from conscribe.registration.registry import _REGISTRY_INDEX, _REGISTRY_INDEX_LOCK

    with _REGISTRY_INDEX_LOCK:
        registries = [_REGISTRY_INDEX[name] for name in sorted(_REGISTRY_INDEX)]
    by_module: dict[str, list[type]] = {}
    for cls in _distinct(cls for registry in registries for _key_, cls in registry.items()):
        by_module.setdefault(str(getattr(cls, "__module__", "")), []).append(cls)
    return by_module


class _InfoCache:
    """:func:`collect_class_stub_info`, once per class."""

    def __init__(self) -> None:
        self._infos: dict[int, ClassStubInfo | None] = {}
        self._keep: list[type] = []

    def get(self, cls: type) -> ClassStubInfo | None:
        if id(cls) not in self._infos:
            self._infos[id(cls)] = collect_class_stub_info(cls)
            self._keep.append(cls)
        return self._infos[id(cls)]


# ── Where stubs go ───────────────────────────────────────────────


def _resolve_output_path(
    classes: list[ClassStubInfo],
    module_name: str,
    output_dir: Path | None,
) -> Path:
    """Where the stub of *module_name* goes (raises when it has nowhere to go)."""
    source_file = next((c.source_file for c in classes if c.source_file), None)
    if output_dir is None:
        names = ", ".join(sorted(c.cls.__qualname__ for c in classes))
        if source_file is None:
            raise ConfigRenderError(
                module_name,
                "<stub>",
                f"module {module_name!r} (class {names})",
                "the module has no source file to write the stub next to; pass output_dir",
            )
        location = _installed_location(source_file)
        if location is not None:
            raise ConfigRenderError(
                module_name,
                "<stub>",
                f"module {module_name!r} (class {names})",
                f"its source {source_file} is part of {location}; conscribe does not write "
                f"stubs into installed code. Pass output_dir (CLI: --output-dir) and put that "
                f"directory on your type checker's stub path",
            )
    path = _stub_path(module_name, source_file, output_dir)
    assert path is not None  # source_file is known when output_dir is None
    return path


def _stub_path(module_name: str, source_file: str | None, output_dir: Path | None) -> Path | None:
    """The stub path of *module_name*; ``None`` when it has none (no source, no output_dir)."""
    if output_dir is None:
        return Path(source_file).with_suffix(".pyi") if source_file else None
    parts = module_name.split(".")
    if _is_package(module_name, source_file):
        return output_dir.joinpath(*parts, "__init__.pyi")
    return output_dir.joinpath(*parts[:-1], parts[-1] + ".pyi")


def _is_package(module_name: str, source_file: str | None) -> bool:
    module = sys.modules.get(module_name)
    if module is not None and hasattr(module, "__path__"):
        return True
    return source_file is not None and Path(source_file).stem == "__init__"


def _module_source_file(classes: Iterable[type]) -> str | None:
    """The source file of the module holding *classes* (as the collector reads it)."""
    for cls in classes:
        try:
            return inspect.getfile(cls)
        except (TypeError, OSError):
            continue
    return None


@functools.lru_cache(maxsize=1)
def _installed_roots() -> tuple[tuple[Path, str], ...]:
    """``(directory, description)`` of the standard library and the site-packages dirs."""
    paths = sysconfig.get_paths()
    roots: dict[Path, str] = {}
    for key in ("stdlib", "platstdlib"):
        if paths.get(key):
            roots.setdefault(Path(paths[key]).resolve(), "the standard library")
    site_dirs: list[str] = [p for p in (paths.get("purelib"), paths.get("platlib")) if p]
    if hasattr(site, "getsitepackages"):  # missing in some virtualenv site modules
        site_dirs.extend(site.getsitepackages())
    if hasattr(site, "getusersitepackages"):
        site_dirs.append(site.getusersitepackages())
    for directory in site_dirs:
        roots.setdefault(Path(directory).resolve(), "an installed package")
    # Most specific first: site-packages usually lives inside the stdlib directory tree.
    return tuple(sorted(roots.items(), key=lambda item: len(item[0].parts), reverse=True))


def _installed_location(source_file: str) -> str | None:
    """What installed code *source_file* belongs to (``None`` for the user's own code)."""
    path = Path(source_file).resolve()
    if any(part in ("site-packages", "dist-packages") for part in path.parts):
        return "an installed package"
    for root, description in _installed_roots():
        if path.is_relative_to(root):
            return description
    return None


def _key(path: Path) -> Path:
    """Comparison key for paths written and found (absolute, symlinks resolved)."""
    return path.resolve()


# ── Stale stubs ──────────────────────────────────────────────────


def _stale_stubs(
    touched: set[str],
    registered: dict[str, list[type]],
    infos: _InfoCache,
    output_dir: Path | None,
    written: set[Path],
) -> list[Path]:
    """Generated stubs in the layer's stub directories that nothing writes or needs.

    A stub is needed when a class registered in a live registry lives in the
    module the stub stands for and needs a stub itself.
    """
    stub_of: dict[Path, list[str]] = {}  # stub path -> modules whose stub it is
    directories: dict[Path, Path] = {}  # key -> directory as built
    for module_name, classes in registered.items():
        source_file = _module_source_file(classes)
        if output_dir is None and (source_file is None or _installed_location(source_file)):
            continue  # nothing is ever written there
        path = _stub_path(module_name, source_file, output_dir)
        if path is None:
            continue
        stub_of.setdefault(_key(path), []).append(module_name)
        if module_name in touched:
            directories.setdefault(_key(path.parent), path.parent)

    stale: list[Path] = []
    for _dir_key, directory in sorted(directories.items()):
        if not directory.is_dir():
            continue
        for candidate in sorted(directory.glob("*.pyi")):
            key = _key(candidate)
            if key in written or not candidate.is_file() or not _is_generated_stub(candidate):
                continue
            modules = stub_of.get(key, [])
            if any(infos.get(cls) is not None for m in modules for cls in registered[m]):
                continue  # another layer's stub, still needed
            stale.append(candidate)
    return stale


def _is_generated_stub(path: Path) -> bool:
    """True when *path* starts with the header conscribe writes into stubs."""
    try:
        with path.open(encoding="utf-8", errors="replace") as handle:
            first, second = handle.readline(), handle.readline()
    except OSError:
        return False
    return any(first.startswith(a) and second.startswith(b) for a, b in _STUB_HEADERS)
