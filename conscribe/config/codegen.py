# The old-shape guard (D6): conscribe's validator on extracted models
# ---------------------------------------------------------------------------


def _legacy_flat_guard(model: type[BaseModel], name: str, decorator: Any, ctx: RenderContext) -> list[str]:
    """Class-body lines reproducing the extractor's old-shape guard.

    1.x flattened a class whose ``__init__`` takes one BaseModel parameter;
    in 2.0 that parameter is a nested block, and the extracted model refuses
    input that still uses the flat keys (error ``legacy_flat_config``, see
    :mod:`conscribe.config.extractor`).  The emitted class gets the same
    ``__legacy_flat_keys__`` table and a ``mode="before"`` model validator
    calling the module-level helper :func:`_legacy_flat_helper` renders once.

    Raises:
        ConfigRenderError: The model carries the guard but no table to check.
    """
    spec = getattr(model, "__legacy_flat_keys__", None)
    if not (
        isinstance(spec, Mapping)
        and isinstance(spec.get("param"), str)
        and isinstance(spec.get("keys"), (tuple, list))
    ):
        raise ConfigRenderError(
            model.__name__, name, describe(spec),
            "the model validates with conscribe's old-shape guard, but carries no "
            "__legacy_flat_keys__ table ({'param': ..., 'keys': (...)}) for it to check",
        )
    ns = ctx.ns
    helper = ctx.module_function(
        "_reject_legacy_flat_keys", _reject_legacy_flat_keys,
        lambda placeholder: _legacy_flat_helper(placeholder, ns),
    )
    any_ = ns.helper("typing", "Any")
    mode = getattr(getattr(decorator, "info", None), "mode", "before")
    return [
        f"__legacy_flat_keys__ = {render_value(dict(spec), ctx)}",
        "",
        f"@{ns.helper('pydantic', 'model_validator')}(mode={mode!r})",
        f"@{ns.builtin('classmethod')}",
        f"def {name}(cls, data: {any_}) -> {any_}:",
        f"    return {helper}(cls, data)",
    ]


def _legacy_flat_helper(placeholder: str, ns: ModuleNamespace) -> str:
    """Source of the module-level old-shape guard (mirrors the extractor's).

    The message template leaves ``{param}`` to pydantic, which fills it from
    the context, so the text equals the in-process one (the extractor
    formats the parameter in itself).
    """
    any_ = ns.helper("typing", "Any")
    return "\n".join([
        "",
        "# conscribe 2.0 old-shape guard: 1.x flattened a class whose __init__ took one",
        "# BaseModel parameter; that parameter is a nested block now, and input still",
        "# using its flat keys is refused with a pointer to the new shape.",
        f"def {placeholder}(cls: {any_}, data: {any_}) -> {any_}:",
        '    spec = getattr(cls, "__legacy_flat_keys__", None)',
        f"    if not spec or not isinstance(data, {ns.helper('collections.abc', 'Mapping')}):",
        "        return data",
        "    accepted = set()",
        "    for field_name, info in cls.model_fields.items():",
        "        accepted.add(field_name)",
        "        for alias in (info.alias, info.validation_alias):",
        "            if isinstance(alias, str):",
        "                accepted.add(alias)",
        '    stale = [key for key in spec["keys"] if key in data and key not in accepted]',
        "    if stale:",
        f"        raise {ns.helper('pydantic_core', 'PydanticCustomError')}(",
        f"            {LEGACY_FLAT_ERROR!r},",
        "            \"'{param}' is a nested block in conscribe 2.0; write {{param}: {...}} \"",
        "            \"or set __config_from_param__ = '{param}'\",",
        '            {"param": spec["param"], "keys": stale},',
        "        )",
        "    return data",
        "",
    ])
