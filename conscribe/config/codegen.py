class _GeneratedFile:
    """Names and blocks of one generated module."""

    def __init__(self) -> None:
        self.ctx = RenderContext()
        self.ctx.register_validator(_reject_legacy_flat_keys, _legacy_flat_guard)
        self.blocks: list[str] = []
        #: Emitted compound discriminators: name -> (placeholder, (fields, separator)).
        self.functions: dict[str, tuple[str, tuple[Any, ...]]] = {}
        self._used: set[str] = set()
        self._reserved: dict[str, str] = {}
        self._titles: dict[int, str] = {}

    # -- naming ------------------------------------------------------------

    def reserve(self, name: str, owner: str) -> None:
        """Reserve a module-level name defined by the layout (alias, function).

        Args:
            name: The name (derived from the layer name ``owner``).
            owner: The layer it belongs to.

        Raises:
            ConfigRenderError: the name is not an identifier, or two layers
                derive the same layout name.
        """
        problem = _identifier_problem(name)
        if problem is not None:
            raise ConfigRenderError(
                owner, "(layer)", repr(name),
                f"the generated name {name!r} derived from layer name {owner!r} is "
                f"{problem}; rename the layer (registry name) to letters, digits and '_'",
            )
        if name in self._reserved:
            raise ConfigRenderError(
                owner, "(layer)", repr(name),
                f"layers {self._reserved[name]!r} and {owner!r} both map to the "
                f"generated name {name!r}; rename one of the layers",
            )
        self._reserved[name] = owner
        self._used.add(name)

    def name_model(self, model: type[BaseModel], *, key: str | None = None, layer: str | None = None) -> str:
        """Give ``model`` its own emitted name (suffixed on collision).

        Args:
            model: The model to define.
            key: The registry key ``model`` was built for (error messages).
            layer: The layer of ``key`` (error messages).

        Raises:
            ConfigRenderError: the model's class name is not an identifier.
        """
        problem = _identifier_problem(model.__name__)
        if problem is not None:
            origin = f" for key {key!r} of layer {layer!r}" if key is not None else ""
            raise ConfigRenderError(
                model.__name__, "(class)", repr(model.__name__),
                f"the config model built{origin} is named {model.__name__!r}, which is "
                f"{problem}; the generated file defines every model under its class "
                f"name, so the model needs a name made of letters, digits and '_'",
            )
        name = self._free(model.__name__)
        self._assign(model, name)
        return name

    def name_submodels(self, submodels: list[type[BaseModel]]) -> list[type[BaseModel]]:
        """Name nested submodels; return them (deepest first) for emission.

        The builders name every model uniquely per build and share
        structurally identical segment models (one object), so each submodel
        keeps its name; :meth:`name_model` still suffixes a clash (e.g. in a
        hand-assembled result) and pins the in-process name as the title.
        """
        for model in submodels:
            self.name_model(model)
        return list(submodels)

    def _free(self, base: str) -> str:
        if base not in self._used:
            return base
        i = 2
        while f"{base}{i}" in self._used:
            i += 1
        return f"{base}{i}"

    def _assign(self, model: type[BaseModel], name: str) -> None:
        self._used.add(name)
        self.ctx.define_model(model, name)
        if name != model.__name__:
            self._titles[id(model)] = model.__name__

    # -- blocks ------------------------------------------------------------

    def model_class(
        self,
        model: type[BaseModel],
        degraded: list[Any] | None = None,
        **options: Any,
    ) -> str:
        """Render ``model`` with ``# wired from:`` / ``# degraded from:`` comments.

        ``options`` are passed to :func:`~conscribe.config._render.render_model_class`
        (``extra_lines``, ``rendered_decorators``, ``class_comments``).
        """
        comments: dict[str, list[str]] = {}
        for df in degraded or getattr(model, "__degraded_fields__", None) or ():
            comments.setdefault(df.field_name, []).append(
                f"degraded from: {df.original_type_repr}"
            )
        for field_name, registry in (getattr(model, "__wired_fields__", None) or {}).items():
            comments.setdefault(field_name, []).append(f"wired from: {registry}")
        return "\n" + render_model_class(
            model, self.ctx, field_comments=comments, title=self._titles.get(id(model)),
            **options,
        )

    def submodels_block(self, emit_list: list[type[BaseModel]]) -> None:
        """Emit nested submodel classes, each followed by ``model_rebuild()``.

        Interleaving ``class`` + ``model_rebuild()`` deepest-first lets every
        shallower class body use a fully built submodel (as a type, or as a
        ``default_factory``).
        """
        if not emit_list:
            return
        parts = ["\n# ── Nested submodels ──"]
        for model in emit_list:
            parts.append(self.model_class(model))
            parts.append(f"{self.ctx.defined_ref(model)}.model_rebuild()")
        parts.append("")
        self.blocks.append("\n".join(parts))

    def rebuild_block(self, models: list[type[BaseModel]]) -> None:
        lines = ["\n# Rebuild models for deferred annotation resolution"]
        lines.extend(f"{self.ctx.defined_ref(m)}.model_rebuild()" for m in models)
        lines.append("")
        self.blocks.append("\n".join(lines))

    def finish(self, header_lines: list[str], degraded: dict[str, list[Any]]) -> str:
        """Assemble header + imports + helpers + blocks; substitute the final names.

        Module-level helpers the rendered classes requested
        (``RenderContext.module_blocks``) come right after the imports.
        """
        ns: ModuleNamespace = self.ctx.ns
        body = "\n".join([*self.ctx.module_blocks.values(), *self.blocks])
        header = _header(header_lines, degraded, self.ctx.notes)
        imports = "\n".join(ns.import_lines()) + "\n"
        text = "\n".join([header, "from __future__ import annotations\n", imports, body])
        return ns.materialize(text)


def _conscribe_version() -> str:
    import conscribe

    return conscribe.__version__


def _header(
    lines: list[str],
    degraded: dict[str, list[Any]],
    notes: list[RenderNote],
) -> str:
    out = [
        f"# Generated by conscribe {_conscribe_version()}",
        "# Auto-generated by conscribe. DO NOT EDIT.",
        *(_comment(line) for line in lines),
    ]
    if degraded:
        out.append("#")
        out.append("# WARNING: The following fields had types incompatible with config")
        out.append("# serialization and were degraded to Any:")
        for key in sorted(degraded):
            field_strs = [
                f"{df.field_name} (was: {df.original_type_repr})" for df in degraded[key]
            ]
            out.append(_comment(f"#   {key}: {', '.join(field_strs)}"))
    if notes:
        out.append("#")
        out.append("# WARNING: The following metadata is enforced only by the in-process")
        out.append("# config model; conscribe cannot write it into this file:")
        for note in notes:
            out.append(_comment(f"#   {note.model}.{note.field}: {note.what}"))
    out.append("")
    return "\n".join(out)


def _warning_messages(ctx: RenderContext) -> list[str]:
    return [note.message() for note in ctx.notes] + list(ctx.warnings)


def _identifier_problem(name: str) -> str | None:
    """Why ``name`` cannot be a module-level name (``None`` when it can)."""
    if keyword.iskeyword(name):
        return "a Python keyword"
    if not name.isidentifier():
        return "not a valid Python identifier"
    return None


def _union_alias_name(layer_name: str) -> str:
    """Per-layer alias name: ``llm`` → ``LLMConfig``, ``agent`` → ``AgentConfig``."""
    if len(layer_name) <= 3:
        return f"{layer_name.upper()}Config"
    return f"{layer_name.title()}Config"


def _composed_alias_name(layer_name: str) -> str:
    """Union alias name in composed files: ``llm`` → ``LLMConfig``, ``foo_bar`` → ``FooBarConfig``."""
    if len(layer_name) <= 3:
        return f"{layer_name.upper()}Config"
    return "".join(seg.title() for seg in layer_name.split("_")) + "Config"


def _composed_alias_names(result: Any) -> dict[str, str]:
    """``{layer: union alias}`` for the multi-key layers of a composed file.

    :func:`_composed_alias_name` of each layer, except that the top-level
    model keeps its name (``ComposedConfig``): a layer whose alias would
    take it (a layer named ``composed``) gets the next free numeric suffix
    (``ComposedConfig2``).  Layers whose aliases collide otherwise are an
    error (:meth:`_GeneratedFile.reserve`).
    """
    top = result.top_level_type.__name__
    aliases: dict[str, str] = {}
    for name in result.dependency_order:
        if len(result.layer_results[name].per_key_models) <= 1:
            continue
        alias = _composed_alias_name(name)
        if alias == top:
            taken = {top, *aliases.values()}
            n = 2
            while f"{alias}{n}" in taken:
                n += 1
            alias = f"{alias}{n}"
        aliases[name] = alias
    return aliases


def _layer_discriminator(result: LayerConfigResult) -> Discriminator | None:
    """The ``Discriminator`` of a nested layer's compound union, if any."""
    _base, disc, _rest = split_discriminated(result.union_type)
    return disc if isinstance(disc, Discriminator) else None


def _discriminator_name(result: LayerConfigResult) -> str:
    """Module-level name of a nested layer's compound discriminator function.

    The in-process function's own ``__name__`` (``_discriminate_<registry
    name>``): pydantic writes it into union errors (``Input tag 'x' found
    using _discriminate_llm() does not match ...``), so the emitted function
    must carry the same name for both artifacts to report the same errors.
    """
    disc = _layer_discriminator(result)
    name = getattr(disc.discriminator, "__name__", None) if disc is not None else None
    if isinstance(name, str) and name.startswith("_discriminate_") and name.isidentifier():
        return name
    return f"_discriminate_{result.layer_name}"


def _alias_block(f: _GeneratedFile, alias: str, result: LayerConfigResult) -> str:
    """``<Alias> = Annotated[Union[...], <discriminator>]`` mirroring ``union_type``.

    Members are written in the in-process union's order so both JSON schemas
    list them identically.
    """
    ctx = f.ctx
    base, disc, rest = split_discriminated(result.union_type)
    if base is None or rest:
        raise ConfigRenderError(
            result.layer_name, "(union)", repr(result.union_type),
            "the layer union is not a plain discriminated union",
        )
    annotated = ctx.ns.helper("typing", "Annotated")
    union = ctx.ns.helper("typing", "Union")
    members = get_args(base)
    if isinstance(disc, str):
        names = ", ".join(ctx.defined_ref(m, where="(union)") for m in members)
        field = ctx.ns.helper("pydantic", "Field")
        return (
            f"\n{alias} = {annotated}[\n"
            f"    {union}[{names}],\n"
            f"    {field}(discriminator={json.dumps(disc)}),\n"
            f"]\n"
        )
    fn = ctx.function_token(disc.discriminator)
    if fn is None:
        raise ConfigRenderError(
            result.layer_name, "(union)", repr(result.union_type),
            "the layer's compound discriminator function was not emitted",
        )
    tag = ctx.ns.helper("pydantic", "Tag")
    lines = []
    for member in members:
        inner, *meta = get_args(member)
        tag_value = next(m.tag for m in meta if isinstance(m, Tag))
        lines.append(
            f"        {annotated}[{ctx.defined_ref(inner, where='(union)')}, {tag}({json.dumps(tag_value)})]"
        )
    return (
        f"\n{alias} = {annotated}[\n"
        f"    {union}[\n" + ",\n".join(lines) + ",\n    ],\n"
        f"    {ctx.ns.helper('pydantic', 'Discriminator')}({fn}),\n"
        f"]\n"
    )


def _discriminator_function(
    f: _GeneratedFile,
    result: LayerConfigResult,
    *,
    layer: str | None = None,
) -> str:
    """Source of the layer's compound discriminator, mirroring the builder's.

    Named like the in-process function (:func:`_discriminator_name`) and
    line for line its logic (``builder._compound_discriminator``): level 0
    is a flat field; level ``i`` walks the nested segment blocks and reads
    their ``name``.  Missing values fall back like the in-process function
    (``""`` at level 0, ``"default"`` below), and when any part is not a
    ``str`` it returns ``None`` -- pydantic then reports
    ``union_tag_not_found`` instead of a raw ``TypeError`` from the join.
    Omitted defaulted blocks need nothing here: their ``default`` tags are
    extra members of the union, which the alias copies.

    A layer whose function is already emitted (the same registrar passed
    under two layer names) reuses it and gets ``""``.

    Args:
        f: The file being generated.
        result: The nested-mode layer.
        layer: The layer's name in a composed build (error messages);
            ``result.layer_name`` when omitted.
    """
    disc = _layer_discriminator(result)
    if disc is None:
        raise ConfigRenderError(
            result.layer_name, "(union)", repr(result.union_type),
            "a nested-mode layer union must carry a Discriminator",
        )
    layer = layer if layer is not None else result.layer_name
    name = _discriminator_name(result)
    fields = list(result.discriminator_fields or [])
    signature = (tuple(fields), result.key_separator)
    emitted = f.functions.get(name)
    if emitted is not None:
        placeholder, emitted_signature = emitted
        if emitted_signature != signature:
            raise ConfigRenderError(
                layer, "(union)", name,
                f"two layers use a compound discriminator named {name!r} with different "
                f"discriminator fields / separators {emitted_signature} and {signature}",
            )
        f.ctx.define_function_as(disc.discriminator, placeholder)
        return ""
    placeholder = f.ctx.define_function(disc.discriminator, name)
    f.functions[name] = (placeholder, signature)
    lines = ["\n# ── Discriminator ──\n", f"def {placeholder}(v):", "    parts = []"]
    lines.append("    if isinstance(v, dict):")
    lines.append(f"        parts.append(v.get({json.dumps(fields[0])}, \"\"))")
    lines.append("    else:")
    lines.append(f"        parts.append(getattr(v, {json.dumps(fields[0])}, \"\"))")
    for i in range(1, len(fields)):
        path = "(" + ", ".join(json.dumps(x) for x in fields[1:i + 1]) + ",)"
        lines.append("    if isinstance(v, dict):")
        lines.append("        nested = v")
        lines.append(f"        for key in {path}:")
        lines.append("            nested = nested.get(key, {}) if isinstance(nested, dict) else {}")
        lines.append(
            "        parts.append(nested.get(\"name\", \"default\") if isinstance(nested, dict) "
            "else getattr(nested, \"name\", \"default\"))"
        )
        lines.append("    else:")
        lines.append("        obj = v")
        lines.append(f"        for key in {path}:")
        lines.append("            obj = getattr(obj, key, None)")
        lines.append("        parts.append(getattr(obj, \"name\", \"default\") if obj else \"default\")")
    lines.append("    if not all(isinstance(part, str) for part in parts):")
    lines.append("        return None")
    lines.append(f"    return {json.dumps(result.key_separator)}.join(parts)")
    lines.append("")
    return "\n".join(lines)


