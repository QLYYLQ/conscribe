"""Python source code generation for config schemas.

Serializes a ``LayerConfigResult`` (one layer) or a ``ComposedConfigResult``
(several layers) into a self-contained Python module of pydantic models
whose JSON schema and validation behaviour equal the in-process models.

This module lays the file out — header, imports, nested submodels, per-key
classes, ``model_rebuild()`` calls, discriminator functions, union aliases,
the top-level ``ComposedConfig`` — and decides which models the file
*defines*: conscribe-generated models only; every other referenced type is
imported by identity.  Rendering of types, defaults and metadata lives in
:mod:`conscribe.config._render`.

Diagnostics:

* :class:`~conscribe.exceptions.ConfigRenderError` — something cannot be
  written faithfully (an unrenderable default, a lambda ``default_factory``,
  a function-local type, an import from conscribe itself).  No file text is
  returned in that case.
* :class:`~conscribe.exceptions.ExtractionWarning` — ``Annotated`` metadata
  the file cannot carry (validators wrapping lambdas, ``Predicate(lambda)``)
  and types imported from ``__main__``.  The in-process model keeps
  enforcing the metadata; the header lists what the file lacks.
"""
from __future__ import annotations

