def generate_layer_config_source(result: LayerConfigResult) -> str:
    """Serialize a ``LayerConfigResult`` to a valid Python source file string.

    Output structure:

    1. Header (``# Generated by conscribe <version>``, layer info, warnings)
    2. ``from __future__ import annotations`` and the import block
    3. Nested segment submodels, deepest first, each with ``model_rebuild()``
    4. Per-key classes and their ``model_rebuild()`` calls
    5. Nested mode: the compound ``_discriminate_<layer>`` function
    6. The union alias (when the layer has more than one key)

    Args:
        result: The ``LayerConfigResult`` from ``build_layer_config()``.

    Returns:
        A string containing valid Python source code.

    Raises:
        ConfigRenderError: a type, default or factory cannot be written
            faithfully into the file.
    """
    if result.discriminator_fields:
        source, ctx = _generate_nested_source(result)
    else:
        source, ctx = _generate_flat_source(result)
    for message in _warning_messages(ctx):
        warnings.warn(message, ExtractionWarning, stacklevel=2)
    return source


def generate_composed_config_source(result: Any) -> str:
    """Serialize a ``ComposedConfigResult`` to Python source code.

    Output structure:

    1. Header (``# Top-level extra: ...``, ``# Inline-only layers: ...``) and
       imports
    2. Nested submodels (deepest first) with ``model_rebuild()``
    3. Per-layer class definitions (in dependency order, leaves first), each
       layer followed by its ``model_rebuild()`` calls and union alias (flat
       ``Field(discriminator=...)`` or, for nested layers, a compound
       ``Discriminator`` callable + ``Tag``; the callable carries the
       in-process function's name, which pydantic writes into union errors)
    4. With inline-only layers: the module-level ``_INLINE_ONLY_WHERE`` table
    5. The top-level ``ComposedConfig`` model -- its ``extra`` policy and
       ``json_schema_extra`` (``x-composed-layers``, ``x-inline-only-layers``,
       ...) as in-process, a hidden phantom field per inline-only layer and
       the ``_refuse_inline_only_layers`` field validator, which refuses any
       value under such a name with the in-process error (type
       ``inline_only_layer``, same message, same location)
    6. ``ComposedConfig.model_rebuild()``, so the file also works exec'd into
       a plain ``dict`` (no module)

    Inline-wired receptor fields render as the target layer's alias when
    they accept every key of the layer, and as an inline discriminated
    ``Annotated[Union[...], ...]`` for a subset, so the file rejects the same
    tag-less blocks the in-process model rejects.  Default instances render
    as ``Field(default_factory=<per-key model>, json_schema_extra={"default":
    ...})``.

    Args:
        result: The ``ComposedConfigResult`` from ``build_composed_config()``.

    Returns:
        A string containing valid Python source code.

    Raises:
        ConfigRenderError: a type, default or factory cannot be written
            faithfully into the file.
    """
    source, ctx = _generate_composed_source(result)
    for message in _warning_messages(ctx):
        warnings.warn(message, ExtractionWarning, stacklevel=2)
    return source


