def _generate_flat_source(result: LayerConfigResult) -> tuple[str, RenderContext]:
    f = _GeneratedFile()
    keys = sorted(result.per_key_models)
    models = [result.per_key_models[k] for k in keys]
    alias = _union_alias_name(result.layer_name) if len(models) > 1 else None
    if alias is not None:
        f.reserve(alias, result.layer_name)
    for key, model in zip(keys, models):
        f.name_model(model, key=key, layer=result.layer_name)
    emit = f.name_submodels(generated_dependencies(models))
    alias_ph = f.ctx.define_alias(result.union_type, alias) if alias is not None else None

    f.submodels_block(emit)
    for key, model in zip(keys, models):
        f.blocks.append(f.model_class(model, result.degraded_fields.get(key)))
    f.rebuild_block(models)
    if alias_ph is not None:
        f.blocks.append(_alias_block(f, alias_ph, result))

    header = [
        f"# Layer: {result.layer_name}",
        f"# Discriminator: {result.discriminator_field}",
        f"# Entries ({len(keys)}): {', '.join(keys)}",
    ]
    return f.finish(header, result.degraded_fields), f.ctx


# ---------------------------------------------------------------------------
# Nested layer (compound discriminator)
# ---------------------------------------------------------------------------


def _generate_nested_source(result: LayerConfigResult) -> tuple[str, RenderContext]:
    f = _GeneratedFile()
    keys = sorted(result.per_key_models)
    models = [result.per_key_models[k] for k in keys]
    multi = len(models) > 1
    alias = _union_alias_name(result.layer_name) if multi else None
    if alias is not None:
        f.reserve(alias, result.layer_name)
        f.reserve(_discriminator_name(result), result.layer_name)
    for key, model in zip(keys, models):
        f.name_model(model, key=key, layer=result.layer_name)
    emit = f.name_submodels(generated_dependencies(models))

    f.submodels_block(emit)
    f.blocks.append("# ── Combined models (level 0 flat + level 1 nested) ──")
    for key, model in zip(keys, models):
        f.blocks.append(f.model_class(model, result.degraded_fields.get(key)))
    f.rebuild_block(models)
    if alias is not None:
        f.blocks.append(_discriminator_function(f, result))
        alias_ph = f.ctx.define_alias(result.union_type, alias)
        f.blocks.append(_alias_block(f, alias_ph, result))

    header = [
        f"# Layer: {result.layer_name}",
        f"# Discriminator fields: {', '.join(result.discriminator_fields or [])}",
        f"# Key separator: {result.key_separator}",
        f"# Entries ({len(keys)}): {', '.join(keys)}",
    ]
    return f.finish(header, result.degraded_fields), f.ctx


