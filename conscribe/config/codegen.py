# Inline-only layers (top-level refusal)
# ---------------------------------------------------------------------------


@dataclasses.dataclass(frozen=True)
class _Refuser:
    """Rendered parts of the top-level inline-only refusal.

    Attributes:
        name: The validator's name (``_refuse_inline_only_layers``).
        layers: The refused layer names (the phantom fields), in field order.
        constant: The module-level ``_INLINE_ONLY_WHERE`` block.
        method: Class-body lines of the field validator.
    """

    name: str
    layers: tuple[str, ...]
    constant: str
    method: tuple[str, ...]


def _inline_only_refuser(f: _GeneratedFile, top: type[BaseModel]) -> _Refuser | None:
    """Render the field validator that refuses values under inline-only layers.

    Reproduces the in-process ``_refuse_inline_only_layers``: the same field
    validator (``mode``, fields), raising ``PydanticCustomError`` with the
    same error type and message template
    (:data:`~conscribe.config.composed.INLINE_ONLY_ERROR_TYPE`,
    :data:`~conscribe.config.composed.INLINE_ONLY_MESSAGE`) and the same
    context: ``where`` is each layer's receptor paths from the model's own
    ``x-inline-only-layers`` schema extra, joined with ``" or "``.

    Returns:
        ``None`` when the model refuses no layer.

    Raises:
        ConfigRenderError: The model's refusal cannot be reproduced (the
            schema extra does not list a refused layer).
    """
    from conscribe.config.composed import (
        _REFUSER_NAME,
        INLINE_ONLY_ERROR_TYPE,
        INLINE_ONLY_MESSAGE,
    )

    decorator = top.__pydantic_decorators__.field_validators.get(_REFUSER_NAME)
    if decorator is None or _REFUSER_NAME not in vars(top):
        return None
    layers = tuple(decorator.info.fields)
    schema_extra = top.model_config.get("json_schema_extra")
    paths = schema_extra.get("x-inline-only-layers") if isinstance(schema_extra, dict) else None
    missing = [layer for layer in layers if not (isinstance(paths, dict) and paths.get(layer))]
    if missing:
        raise ConfigRenderError(
            top.__name__, _REFUSER_NAME, repr(missing),
            "the model refuses these inline-only layers, but its "
            "json_schema_extra['x-inline-only-layers'] does not list where their "
            "instances belong, so the generated refusal could not name it",
        )
    where = {layer: " or ".join(paths[layer]) for layer in layers}  # type: ignore[index]

    ns = f.ctx.ns
    constant = ns.define("_INLINE_ONLY_WHERE", where)
    str_ = ns.builtin("str")
    any_ = ns.helper("typing", "Any")
    entries = "".join(f"    {layer!r}: {text!r},\n" for layer, text in where.items())
    constant_block = (
        "\n# Where the instances of each inline-only layer are written instead.\n"
        f"{constant}: {ns.builtin('dict')}[{str_}, {str_}] = {{\n"
        f"{entries}}}\n"
    )
    fields = ", ".join(repr(layer) for layer in layers)
    mode = getattr(decorator.info, "mode", "after")
    method = (
        f"@{ns.helper('pydantic', 'field_validator')}({fields}, mode={mode!r})",
        f"@{ns.builtin('classmethod')}",
        f"def {_REFUSER_NAME}(cls, value: {any_}, "
        f"info: {ns.helper('pydantic', 'ValidationInfo')}) -> {any_}:",
        '    """Refuse any value written under an inline-only layer\'s name."""',
        f"    layer = {str_}(info.field_name)",
        f"    raise {ns.helper('pydantic_core', 'PydanticCustomError')}(",
        f"        {INLINE_ONLY_ERROR_TYPE!r},",
        f"        {INLINE_ONLY_MESSAGE!r},",
        f"        {{'layer': layer, 'where': {constant}[layer]}},",
        "    )",
    )
    return _Refuser(_REFUSER_NAME, layers, constant_block, method)


