def _generate_composed_source(result: Any) -> tuple[str, RenderContext]:
    f = _GeneratedFile()
    order: list[str] = list(result.dependency_order)
    layers = {name: result.layer_results[name] for name in order}

    # The top-level model keeps its in-process name; layer aliases yield.
    top = result.top_level_type
    f.name_model(top)
    aliases = _composed_alias_names(result)
    discriminators: set[str] = set()
    for name, lr in layers.items():
        if name in aliases:
            f.reserve(aliases[name], name)
            if lr.discriminator_fields:
                function = _discriminator_name(lr)
                if function not in discriminators:  # one registrar under two names
                    discriminators.add(function)
                    f.reserve(function, name)

    per_layer: dict[str, list[tuple[str, type[BaseModel]]]] = {}
    for name, lr in layers.items():
        per_layer[name] = [(k, lr.per_key_models[k]) for k in sorted(lr.per_key_models)]
        for key, model in per_layer[name]:
            f.name_model(model, key=key, layer=name)
    all_models = [m for entries in per_layer.values() for _k, m in entries]
    emit = f.name_submodels(generated_dependencies([*all_models, top]))

    f.submodels_block(emit)
    for name, lr in layers.items():
        f.blocks.append(f"\n# ── Layer: {name} ──\n")
        for key, model in per_layer[name]:
            f.blocks.append(f.model_class(model, lr.degraded_fields.get(key)))
        f.rebuild_block([m for _k, m in per_layer[name]])
        if name in aliases:
            if lr.discriminator_fields:
                function = _discriminator_function(f, lr, layer=name)
                if function:
                    f.blocks.append(function)
            alias_ph = f.ctx.define_alias(lr.union_type, aliases[name])
            f.blocks.append(_alias_block(f, alias_ph, lr))

    refuser = _inline_only_refuser(f, top)
    extra = top.model_config.get("extra") or "ignore"
    f.blocks.append("\n# ── Composed Config ──\n")
    if refuser is not None:
        f.blocks.append(refuser.constant)
    f.blocks.append(f.model_class(
        top,
        extra_lines=refuser.method if refuser is not None else (),
        rendered_decorators=[refuser.name] if refuser is not None else (),
        class_comments=_top_level_comments(extra, refuser),
    ))
    # The top-level model refers to every layer alias; rebuilding it resolves
    # them also when the file is exec'd into a plain dict (no module).
    f.rebuild_block([top])

    header = [
        f"# Composed config: {', '.join(order)}",
        f"# Inline wiring: {result.inline_wiring}",
        f"# Top-level extra: {extra}",
    ]
    if refuser is not None:
        header.append(f"# Inline-only layers: {', '.join(refuser.layers)}")
    degraded: dict[str, list[Any]] = {}
    for name, lr in layers.items():
        for key, fields in lr.degraded_fields.items():
            degraded[f"{name}.{key}"] = fields
    return f.finish(header, degraded), f.ctx


def _top_level_comments(extra: str, refuser: _Refuser | None) -> list[str]:
    """Comment lines opening the ``ComposedConfig`` class body."""
    comments = {
        "forbid": ["Unknown top-level keys are refused (top_level_extra='forbid')."],
        "ignore": ["Unknown top-level keys are dropped (top_level_extra='ignore')."],
        "allow": ["Unknown top-level keys are kept in model_extra (top_level_extra='allow')."],
    }.get(extra, [])
    if refuser is not None:
        comments.append(
            "Inline-only layers have no section: a value under their name is refused "
            "(see _refuse_inline_only_layers)."
        )
    return comments


